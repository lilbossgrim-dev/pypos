"""Render the initial Alembic migration from the core collection specs.

The migration file is generated (``scripts/gen_migration.py``) and committed so the
schema history is frozen; a test fails if the committed file drifts from the specs.
"""

from __future__ import annotations

from pypos.persistence.schema import ID_LENGTH, KEY_LENGTH, MERCHANT_LENGTH, describe
from pypos.persistence.specs import CORE_SPECS

HEADER = '''"""initial schema (generated by scripts/gen_migration.py - do not edit by hand)

Revision ID: 0001_initial
Revises:
"""

import sqlalchemy as sa
from alembic import op
from sqlalchemy.dialects import postgresql

revision = "0001_initial"
down_revision = None
branch_labels = None
depends_on = None

JSON = sa.JSON().with_variant(postgresql.JSONB(), "postgresql")
'''


def render_initial_migration() -> str:
    defs = [describe(spec) for spec in CORE_SPECS]
    out = [HEADER, "\n\ndef upgrade() -> None:\n"]
    for d in defs:
        out.append(f"    op.create_table(\n        {d.name!r},\n")
        out.append(f'        sa.Column("id", sa.String({ID_LENGTH}), primary_key=True),\n')
        out.append(
            f'        sa.Column("merchant_id", sa.String({MERCHANT_LENGTH}), nullable=False),\n'
        )
        out.append('        sa.Column("version", sa.Integer(), nullable=False),\n')
        out.append('        sa.Column("created_at", sa.DateTime(timezone=True), nullable=False),\n')
        out.append('        sa.Column("updated_at", sa.DateTime(timezone=True), nullable=False),\n')
        out.append('        sa.Column("data", JSON, nullable=False),\n')
        for c in d.key_columns:
            out.append(f"        sa.Column({c!r}, sa.String({KEY_LENGTH}), nullable=True),\n")
        for name, cols in d.uniques:
            out.append(
                f"        sa.UniqueConstraint({', '.join(repr(c) for c in cols)}, name={name!r}),\n"
            )
        out.append("    )\n")
        for name, cols in d.indexes:
            out.append(f"    op.create_index({name!r}, {d.name!r}, {list(cols)!r})\n")
    out.append("\n\ndef downgrade() -> None:\n")
    for d in reversed(defs):
        for name, _ in reversed(d.indexes):
            out.append(f"    op.drop_index({name!r}, table_name={d.name!r})\n")
        out.append(f"    op.drop_table({d.name!r})\n")
    return "".join(out)
